    internal static IReadOnlySet<uint> GetRequiredItemIds(IEnumerable<(string Instruction, uint ItemId)> symbols) =>
        symbols.Where(x => x.ItemId > 0 && x.Instruction.StartsWith("RITEM", StringComparison.Ordinal) &&
                           uint.TryParse(x.Instruction.AsSpan(5), NumberStyles.None, CultureInfo.InvariantCulture, out _))
            .Select(x => x.ItemId)
            .ToHashSet();

    internal static IReadOnlyList<CraftingItem> GetItems(ElementId questId) =>
        questId is QuestId && Items.TryGetValue(questId.Value, out var items) ? items : [];

    internal static CraftingItem ResolveItem(ElementId questId, CraftingItem requested)
    {
        CraftingItem? required = GetItems(questId).FirstOrDefault(x => x.ItemId == requested.ItemId);
        return required == null ? requested : requested with
        {
            ItemCount = Math.Max(requested.ItemCount, required.ItemCount),
            Quality = required.Quality == EItemQuality.HQ ? EItemQuality.HQ : requested.Quality,
        };
    }

    // Only these reviewed legacy paths omit their targets. Do not reapply requirements at another stage.
    internal static IReadOnlyList<CraftingItem> GetLegacyItems(ElementId questId, byte sequence) =>
        questId is QuestId && (questId.Value, sequence) is
            (139, 255) or (140, 255) or (141, 2) or (142, 255) or (168, 255) or (205, 255) or
            (2044, 255) or (2045, 255) or (2046, 255) or (2047, 3)
            ? GetItems(questId)
            : [];

